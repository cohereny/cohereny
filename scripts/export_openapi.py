#!/usr/bin/env python3
"""
scripts/export_openapi.py

Write the OpenAPI specification to openapi.yaml (CHY-28, ADR-029).

CHY-28 originally asked for the opposite: hand-write `core/openapi.yaml` before
the implementation, so the GUI could be built against a Prism mock. Every part
of that premise has expired — the API exists, is deployed on three stages, and
cohereny-ui talks to the real thing. A hand-written spec next to it would be a
second source of truth, and the two would drift; that is the failure this
project keeps finding in its own foundations.

So the direction is reversed. The code is the specification. This script writes
a snapshot of it into the repository, and tests/test_openapi_contract.py fails
when the snapshot and the application disagree.

Since CHY-109 it writes five files, not one: the whole API in openapi.yaml, and
one contract per consumer surface in contracts/. The per-surface files are the
enforceable half of interface segregation — a consumer generating a client from
contracts/openapi-serve.yaml cannot call an admin endpoint, because it does not
know one exists. The gate in api/surfaces.py refuses at runtime; these refuse at
build time, which is cheaper for everyone.

What that buys, now that it cannot buy parallel development:
  Every contract change shows up as a reviewable diff in the merge request. A
  renamed field, a removed endpoint, a status code that quietly became 200 — all
  of them become something a human said yes to, instead of something that
  shipped. That is the whole point, and it only works because nobody can edit
  the YAML directly and have it stick.

Usage:
    python scripts/export_openapi.py          # write all five
    python scripts/export_openapi.py --check  # exit 1 if any is out of date

Dependencies:
  - pyyaml (already a project dependency)
"""
from __future__ import annotations

import argparse
import os
import pathlib
import sys

import yaml

# Import order matters: api.config reads the environment at import time, and a
# missing DATABASE_URL would abort before the app object exists. Nothing is
# connected here — only the schema is built — so a placeholder is honest.
#
# DEV_MODE used to be set here too, and it was never needed: it only decided
# docs_url and openapi_url, neither of which appears in the generated schema —
# verified by diffing the output with and without. It did two kinds of harm.
# It leaked into os.environ for every test that imports this module, which is
# how two settings tests failed only in the full suite and passed alone. And
# with the CHY-91 guard in place it would have refused to construct Settings,
# breaking the export. The switch itself is gone since CHY-192.
os.environ.setdefault("DATABASE_URL", "postgresql://export:export@localhost/export")

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))

from api.main import app
from api.v1.router import SURFACE_PATHS
from kernel.surfaces import AUDIENCES, Surface

_ROOT = pathlib.Path(__file__).resolve().parent.parent
SPEC_PATH = _ROOT / "openapi.yaml"
CONTRACTS_DIR = _ROOT / "contracts"

_HEADER = """\
# Generated by scripts/export_openapi.py — do not edit by hand.
#
# The application is the source of this contract (ADR-029). Editing this file
# changes nothing about the API and will fail tests/test_openapi_contract.py.
# To change the contract, change the routes and run the script again.
"""


def _dump(spec: dict) -> str:
    """The spec as deterministic YAML.

    sort_keys=True is not cosmetic: without it the path order follows router
    registration, so moving a route in the source produces a diff that touches
    the whole file and hides the change that actually happened.
    """
    return _HEADER + yaml.safe_dump(
        spec, sort_keys=True, allow_unicode=True, default_flow_style=False, width=100,
    )


def _referenced_schemas(node: object, components: dict, seen: set[str]) -> set[str]:
    """Every schema reachable from `node`, following $ref transitively.

    Without this the per-surface files would each carry all 60-odd models, which
    would undo the point: a consumer is meant to see what it can call, and a
    generated client would still produce classes for everything else.

    Recursive because schemas reference schemas — a response model holds a list
    of items that hold an enum. Stopping at depth one produced a contract with
    dangling $refs, which is worse than an oversized one.
    """
    if isinstance(node, dict):
        ref = node.get("$ref")
        if isinstance(ref, str) and ref.startswith("#/components/schemas/"):
            name = ref.rsplit("/", 1)[1]
            if name not in seen:
                seen.add(name)
                _referenced_schemas(components.get(name, {}), components, seen)
        for value in node.values():
            _referenced_schemas(value, components, seen)
    elif isinstance(node, list):
        for item in node:
            _referenced_schemas(item, components, seen)
    return seen


def render(surface: Surface | None = None) -> str:
    """The whole contract, or the part of it one surface publishes."""
    spec = app.openapi()
    if surface is None:
        return _dump(spec)

    keep = SURFACE_PATHS[surface.value]
    spec = {**spec, "paths": {p: v for p, v in spec["paths"].items() if p in keep}}

    components = spec.get("components", {}).get("schemas", {})
    if components:
        used = _referenced_schemas(spec["paths"], components, set())
        spec["components"] = {
            **spec["components"],
            "schemas": {k: v for k, v in components.items() if k in used},
        }

    spec["info"] = {
        **spec["info"],
        "title": f"{spec['info']['title']} — {surface.value}",
        "description": (
            f"The {surface.value} surface (ADR-031). Tokens for this contract "
            f"carry the audience `{AUDIENCES[surface.value]}`; the API refuses "
            f"them anywhere else.\n\n"
            f"Generated from the application — see scripts/export_openapi.py."
        ),
    }
    return _dump(spec)


def _targets() -> list[tuple[pathlib.Path, str]]:
    """Every file this script owns, with the text it should contain."""
    out = [(SPEC_PATH, render())]
    out += [(CONTRACTS_DIR / f"openapi-{s.value}.yaml", render(s)) for s in Surface]
    return out


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--check", action="store_true", help="Do not write; report drift.")
    args = p.parse_args()

    targets = _targets()
    stale = [path for path, text in targets
             if not path.exists() or path.read_text(encoding="utf-8") != text]

    if args.check:
        if not stale:
            print(f"{len(targets)} contracts up to date")
            return 0
        for path in stale:
            print(f"{path.relative_to(_ROOT)} is out of date", file=sys.stderr)
        print("run: python scripts/export_openapi.py", file=sys.stderr)
        return 1

    CONTRACTS_DIR.mkdir(exist_ok=True)
    for path, text in targets:
        if path in stale:
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(_ROOT)}")
    if not stale:
        print(f"{len(targets)} contracts unchanged")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
