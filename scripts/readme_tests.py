#!/usr/bin/env python3
"""
scripts/readme_tests.py

The measured part of the "Tests" section in README.md, generated (CHY-230).

On 2026-11-04 the snapshot went out saying 1,382 unit tests and 70 integration
tests, measured on 30.10. and typed in by hand. By then there were 1,563 and
71, and nothing noticed: a number somebody copies goes stale without a sound.
This script measures instead and writes what is a measurement — the two
counts, the line coverage per directory, the date and the tools — between two
markers in README.md. The text around it stays by hand: what pulls the figure
down and what the `quality` job checks is a judgement, not a number.

What it runs, from the repository root:

    pytest tests/ pilots/banking/tests pilots/study/tests --cov   (must pass)
    pytest -m integration tests/integration --collect-only        (counted only)

The integration tests need a PostgreSQL and are counted, not run; the
`integration` job runs them on every push. A unit run with a failure writes
nothing — a section generated from a red run would publish a number the code
does not earn.

Usage:
    python scripts/readme_tests.py            # measure, rewrite the section
    python scripts/readme_tests.py --dry-run  # measure, print the section

Part of the snapshot routine, before the release to main (CHY-250).
"""
from __future__ import annotations

import argparse
import datetime
import json
import pathlib
import re
import subprocess
import sys
import tempfile
from decimal import ROUND_HALF_UP, Decimal
from importlib.metadata import version

ROOT = pathlib.Path(__file__).resolve().parent.parent
README = ROOT / "README.md"

BEGIN = "<!-- BEGIN generated by scripts/readme_tests.py -->"
END = "<!-- END generated by scripts/readme_tests.py -->"

UNIT_PATHS = ["tests/", "pilots/banking/tests", "pilots/study/tests"]

#: The directories outside the pilots, with what each holds. A directory that
#: coverage reports and this list does not name stops the script: it would
#: count in the total without a row of its own.
DIRECTORIES = {
    "router": "Routing rules",
    "kernel": "Identity, roles, permissions, audit",
    "api": "HTTP transport",
    "contexts": "Context repository, orchestration, learning, pilot runs",
    "core": "Database pool, Redis, tracing",
    "cli": "Command line",
}
PILOTS = ("pilots/banking", "pilots/study")


def percent(covered: int, statements: int) -> int:
    """A whole percent, rounded half up — 74.5 is 75, as a reader would round."""
    if statements == 0:
        return 0
    exact = Decimal(covered) * 100 / Decimal(statements)
    return int(exact.quantize(Decimal(1), rounding=ROUND_HALF_UP))


def by_directory(coverage: dict) -> dict[str, tuple[int, int]]:
    """(covered lines, statements) per top-level directory; pilots per pilot.

    From the JSON report of coverage.py, whose `files` are keyed by path
    relative to the repository root.
    """
    out: dict[str, tuple[int, int]] = {}
    for path, data in coverage["files"].items():
        parts = pathlib.PurePosixPath(path).parts
        key = "/".join(parts[:2]) if parts[0] == "pilots" else parts[0]
        covered, statements = out.get(key, (0, 0))
        summary = data["summary"]
        out[key] = (covered + summary["covered_lines"],
                    statements + summary["num_statements"])
    unknown = sorted(set(out) - set(DIRECTORIES) - set(PILOTS))
    if unknown:
        message = f"coverage reports directories without a row: {', '.join(unknown)}"
        raise ValueError(message)
    return out


def passed_count(output: str) -> int:
    """The number of passed tests from pytest's summary line.

    Refuses a run with a failure or an error.
    """
    summary = output.strip().splitlines()[-1] if output.strip() else ""
    if re.search(r"\d+ (failed|errors?)\b", summary):
        message = f"the unit tests did not pass: {summary}"
        raise ValueError(message)
    found = re.search(r"(\d+) passed", summary)
    if not found:
        message = f"no pytest summary found: {summary!r}"
        raise ValueError(message)
    return int(found.group(1))


def collected_count(output: str) -> int:
    """The number of collected tests from `pytest --collect-only -q`."""
    found = re.search(r"(\d+)(?:/\d+)? tests? collected", output)
    if not found:
        message = "no collection count found"
        raise ValueError(message)
    return int(found.group(1))


def render(unit: int, integration: int, coverage: dict,
           date: datetime.date, versions: dict[str, str]) -> str:
    """The generated block, markers included."""
    dirs = by_directory(coverage)
    rows = sorted(DIRECTORIES, key=lambda d: (-percent(*dirs.get(d, (0, 0))), d))
    outside = (sum(dirs.get(d, (0, 0))[0] for d in DIRECTORIES),
               sum(dirs.get(d, (0, 0))[1] for d in DIRECTORIES))
    totals = coverage["totals"]
    pilots = ", ".join(f"{percent(*dirs.get(p, (0, 0)))} %" for p in PILOTS)
    lines = [
        BEGIN,
        f"{unit:,} unit tests need no services; another {integration:,} run against a real PostgreSQL.",
        f"The unit tests alone cover **{percent(*outside)} %** of the lines outside the two pilots:",
        "",
        "| Directory | What it holds | Line coverage |",
        "|---|---|---|",
        *(f"| `{d}/` | {DIRECTORIES[d]} | {percent(*dirs.get(d, (0, 0)))} % |" for d in rows),
        f"| **All of the above** | | **{percent(*outside)} %** |",
        f"| {', '.join(f'`{p}/`' for p in PILOTS)} | The two original pilots | {pilots} |",
        (f"| **Including the pilots** | | "
         f"**{percent(totals['covered_lines'], totals['num_statements'])} %** |"),
        "",
        (f"Measured on {date.isoformat()} with Python {versions['python']}, "
         f"pytest {versions['pytest']} and coverage {versions['coverage']}:"),
        f"`pytest {' '.join(UNIT_PATHS)} --cov`",
        END,
    ]
    return "\n".join(lines)


def replace_section(text: str, block: str) -> str:
    """`text` with the part between the markers replaced by `block`.

    Exactly one pair, in order — anything else is a README somebody edited by
    hand around the markers, and guessing would overwrite their text.
    """
    if text.count(BEGIN) != 1 or text.count(END) != 1 or text.index(BEGIN) > text.index(END):
        message = "README.md needs exactly one pair of readme_tests markers, BEGIN before END"
        raise ValueError(message)
    head, rest = text.split(BEGIN)
    _, tail = rest.split(END)
    return head + block + tail


def _minor(version: str) -> str:
    """'3.14.6' → '3.14': the reader needs the line, not the patch."""
    return ".".join(version.split(".")[:2])


def _pytest(*args: str) -> str:
    result = subprocess.run([sys.executable, "-m", "pytest", *args, "-p", "no:cacheprovider"],
                            cwd=ROOT, capture_output=True, text=True, check=False)
    return result.stdout


def measure() -> tuple[int, int, dict, dict[str, str]]:
    """Run the unit tests with coverage and count the integration tests."""
    with tempfile.TemporaryDirectory() as tmp:
        report = pathlib.Path(tmp) / "coverage.json"
        out = _pytest(*UNIT_PATHS, "--cov", f"--cov-report=json:{report}", "-q")
        unit = passed_count(out)
        coverage = json.loads(report.read_text())
    integration = collected_count(_pytest("-m", "integration", "tests/integration",
                                          "--collect-only", "-q"))
    versions = {
        "python": _minor(".".join(map(str, sys.version_info[:3]))),
        "pytest": _minor(version("pytest")),
        "coverage": _minor(version("coverage")),
    }
    return unit, integration, coverage, versions


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python scripts/readme_tests.py",
                                     description="Generate the measured part of the README's Tests section (CHY-230).")
    parser.add_argument("--dry-run", action="store_true", help="print the section, change nothing")
    args = parser.parse_args(argv)

    try:
        unit, integration, coverage, versions = measure()
        today = datetime.datetime.now(tz=datetime.UTC).date()
        block = render(unit, integration, coverage, today, versions)
        updated = replace_section(README.read_text(encoding="utf-8"), block)
    except ValueError as exc:
        print(f"readme_tests: {exc}", file=sys.stderr)
        return 1
    if args.dry_run:
        print(block)
        return 0
    README.write_text(updated, encoding="utf-8")
    print(f"readme_tests: {unit:,} unit, {integration:,} integration tests written to README.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
